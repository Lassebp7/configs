#!/usr/bin/env bash
# Installs the shared and profile-specific AI instructions, skills and agents into OpenCode and Claude Code.
#   AGENTS.md: ai/AGENTS.md + profiles/<profile>/ai/AGENTS.md -> ~/.config/opencode/AGENTS.md, ~/.claude/CLAUDE.md
#   skills:    each skill folder is symlinked into both tools' skills/ folder
#   agents:    prompt.md + opencode.yaml / claude.yaml are combined into one agent file per tool
# Profile skills and agents replace shared ones with the same name.
# Usage: build-ai.sh [profile]   (defaults to the saved profile)
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

profile="${1:-$(saved_profile)}"
[[ -n "$profile" ]] || die "no profile given and none saved in $PROFILE_FILE"
sources=("$REPO/ai" "$REPO/profiles/$profile/ai")

opencode_dir="$HOME/.config/opencode"
claude_dir="$HOME/.claude"
marker="Generated by ~/code/configs/scripts/build-ai.sh"

# Replaces a symlink or an unmanaged file/folder so we can write our own at that path
take_over() {
  local path="$1"
  if [[ -L "$path" ]]; then
    rm "$path"
  elif [[ -e "$path" ]] && ! grep -qsF "$marker" "$path"; then
    backup "$path"
  fi
}

ensure_dir() {
  local dir="$1"
  if [[ -L "$dir" ]]; then rm "$dir"; fi
  mkdir -p "$dir"
}

frontmatter() { awk 'NR==1 && /^---$/ { fm=1; next } fm && /^---$/ { exit } fm' "$1"; }
body() { awk 'NR==1 && /^---$/ { fm=1; next } fm && /^---$/ { fm=0; next } !fm' "$1"; }

build_instructions() {
  local content="<!-- $marker. Edit the source files instead. -->"$'\n' file
  for src in "${sources[@]}"; do
    file="$src/AGENTS.md"
    [[ -f "$file" ]] && content+=$'\n'"$(cat "$file")"$'\n'
  done
  for target in "$opencode_dir/AGENTS.md" "$claude_dir/CLAUDE.md"; do
    mkdir -p "$(dirname "$target")"
    take_over "$target"
    printf '%s' "$content" >"$target"
  done
}

build_skills() {
  declare -A skills=()
  local src dir name tool_dir
  for src in "${sources[@]}"; do
    for dir in "$src"/skills/*/; do
      [[ -d "$dir" ]] && skills[$(basename "$dir")]="${dir%/}"
    done
  done

  for tool_dir in "$opencode_dir/skills" "$claude_dir/skills"; do
    ensure_dir "$tool_dir"
    # Drop links to skills that were removed from the repo or belong to another profile
    find "$tool_dir" -mindepth 1 -maxdepth 1 -type l -lname "$REPO/*" -delete
    for name in "${!skills[@]}"; do
      if [[ -e "$tool_dir/$name" && ! -L "$tool_dir/$name" ]]; then backup "$tool_dir/$name"; fi
      ln -sfn "${skills[$name]}" "$tool_dir/$name"
    done
  done
}

# Writes one agent file: shared frontmatter from prompt.md, the tool's own keys, then the prompt
write_agent() {
  local dir="$1" tool_yaml="$2" target="$3" name_line="$4"
  take_over "$target"
  {
    echo "---"
    echo "# $marker from ${dir#"$REPO"/}"
    [[ -n "$name_line" ]] && echo "$name_line"
    frontmatter "$dir/prompt.md"
    cat "$tool_yaml"
    echo "---"
    body "$dir/prompt.md"
  } >"$target"
}

build_agents() {
  declare -A agents=()
  local src dir name tool_dir
  for src in "${sources[@]}"; do
    for dir in "$src"/agents/*/; do
      [[ -f "$dir/prompt.md" ]] && agents[$(basename "$dir")]="${dir%/}"
    done
  done

  for tool_dir in "$opencode_dir/agents" "$claude_dir/agents"; do
    ensure_dir "$tool_dir"
    { grep -lsF "$marker" "$tool_dir"/*.md || true; } | xargs -r rm --
  done

  for name in "${!agents[@]}"; do
    dir="${agents[$name]}"
    if [[ -f "$dir/opencode.yaml" ]]; then
      write_agent "$dir" "$dir/opencode.yaml" "$opencode_dir/agents/$name.md" ""
    fi
    if [[ -f "$dir/claude.yaml" ]]; then
      write_agent "$dir" "$dir/claude.yaml" "$claude_dir/agents/$name.md" "name: $name"
    fi
  done
}

info "Building AI instructions, skills and agents for profile '$profile'"
build_instructions
build_skills
build_agents
